/** Strict fallback chains (chunk 4B): hi -> hi-Latn -> en; hinglish -> en. */
export function t(lang: UiLang, key: DictKey): string {
  if (lang === 'hi') return HI[key] ?? HINGLISH[key] ?? EN[key];
  if (lang === 'hinglish') return HINGLISH[key] ?? EN[key];
  return EN[key];
}

/** Convenience: translate for a LumioState profile language (defaults to English). */
export function tFor(lang: UiLang | undefined | null): (key: DictKey) => string {
  return (key: DictKey) => t(lang ?? 'en', key);
}

export function isUiLang(v: unknown): v is UiLang {
  return v === 'en' || v === 'hi' || v === 'hinglish';
}

/** 'daily-plan-review' -> DictKey 'quest.dailyPlanReview.title' | '.desc' */
function questDictKey(questId: string, kind: 'title' | 'desc'): DictKey {
  const camel = questId
    .split('-')
    .map((part, i) => (i === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)))
    .join('');
  return `quest.${camel}.${kind}` as DictKey;
}

export function questTitle(lang: UiLang, questId: string, fallback: string): string {
  const key = questDictKey(questId, 'title');
  return lang === 'en' ? fallback : t(lang, key) || fallback;
}

export function questDesc(lang: UiLang, questId: string, fallback: string): string {
  const key = questDictKey(questId, 'desc');
  return lang === 'en' ? fallback : t(lang, key) || fallback;
}
